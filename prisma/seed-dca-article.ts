async function main() {
  console.log('🌱 Seeding DCA Tax Planning 2569 Article...');

  const authorWichian = await prisma.author.findUnique({
    where: { slug: 'wichian-deethavorn' },
  });

  const authorTaxTeam = await prisma.author.findUnique({
    where: { slug: 'deethavorn-tax-editorial' },
  });

  const authorId = authorWichian?.id ?? 1;
  const reviewerId = authorTaxTeam?.id ?? 2;

  const seoResult = analyzeSeoScore({
    title: dcaArticlePayload.title,
    slug: dcaArticlePayload.slug,
    summary: dcaArticlePayload.summary,
    contentMarkdown: dcaArticlePayload.contentMarkdown,
    focusKeyword: dcaArticlePayload.focusKeyword,
    coverImage: dcaArticlePayload.coverImage,
    coverImageAlt: dcaArticlePayload.coverImageAlt,
    faqs: dcaArticlePayload.faqs,
    citations: dcaArticlePayload.citations,
    authorId,
    reviewerId,
  });

  console.log(`📊 Calculated SEO Score: ${seoResult.score}/100 (${seoResult.status})`);

  const { faqs, citations, ...articleData } = dcaArticlePayload;

  const upsertedArticle = await prisma.article.upsert({
    where: { slug: dcaArticlePayload.slug },
    update: {
      ...articleData,
      seoScore: seoResult.score,
      authorId,
      reviewerId,
    },
    create: {
      ...articleData,
      seoScore: seoResult.score,
      authorId,
      reviewerId,
    },
  });

  await prisma.articleFaq.deleteMany({ where: { articleId: upsertedArticle.id } });
  await prisma.articleFaq.createMany({
    data: faqs.map((f) => ({ ...f, articleId: upsertedArticle.id })),
  });

  await prisma.articleCitation.deleteMany({ where: { articleId: upsertedArticle.id } });
  await prisma.articleCitation.createMany({
    data: citations.map((c) => ({ ...c, articleId: upsertedArticle.id })),
  });

  console.log(`✅ Successfully seeded article: "${upsertedArticle.title}" (Slug: ${upsertedArticle.slug})`);
}

if (require.main === module) {
  main()
    .catch((e) => {
      console.error('❌ Error seeding DCA article:', e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
