export function getSubServiceBySlug(slug: string): SubServiceDetailConfig | undefined {
  return SUB_SERVICES.find((item) => item.slug === slug);
}

export function getRelatedSubServices(
  parentCategorySlug: SubServiceDetailConfig['parentCategorySlug'],
  excludeSlug: string
): SubServiceDetailConfig[] {
  return SUB_SERVICES.filter(
    (item) => item.parentCategorySlug === parentCategorySlug && item.slug !== excludeSlug
  );
}
